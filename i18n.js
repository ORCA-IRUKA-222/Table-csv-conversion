(() => {
  const pick = () => {
    const q = new URLSearchParams(location.search).get('lang');
    if (q && LANGS[q]) return q;
    try {
      const saved = localStorage.getItem('lang');
      if (saved && LANGS[saved]) return saved;
    } catch { /* プライベートモードでは保存できない */ }
    for (const tag of navigator.languages || [navigator.language || '']) {
      if (LANGS[tag]) return tag;
      const base = String(tag).split('-')[0];
      const hit = Object.keys(LANGS).find((c) => c === base || c.split('-')[0] === base);
      if (hit) return hit;
    }
    return 'en';
  };

  const apply = (lang) => {
    const dict = T[lang] || T.en;
    document.documentElement.lang = lang;
    for (const el of document.querySelectorAll('[data-i18n]')) {
      const v = dict[el.dataset.i18n] ?? T.en[el.dataset.i18n];
      if (v != null) el.textContent = v;
    }
    if (!document.documentElement.hasAttribute('data-no-auto-title')) {
      const title = dict.title || T.en.title;
      if (title) document.title = title;
      const meta = document.querySelector('meta[name="description"]');
      if (meta) meta.content = dict.metaDesc || T.en.metaDesc;
    }
  };

  const select = document.getElementById('lang');
  const lang = pick();
  apply(lang);

  if (select) {
    for (const [code, name] of Object.entries(LANGS)) select.append(new Option(name, code));
    select.value = lang;
    select.addEventListener('change', () => {
      try { localStorage.setItem('lang', select.value); } catch { /* 保存できなくても表示は切り替える */ }
      apply(select.value);
      const url = new URL(location.href);
      url.searchParams.set('lang', select.value);
      history.replaceState(null, '', url);
    });
  }
})();
